const adjH = (s) => ["ый", "ая", "ое", "ые", "ого", "ой", "ому", "ым", "ую", "ом", "ых", "ыми"].map((e) => s + e);
const adjS = (s) => ["ий", "ая", "ее", "ие", "его", "ей", "ему", "им", "ую", "ем", "их", "ими"].map((e) => s + e);
const sfx = (f) => (/[аеёиоуыэюя]$/.test(f) ? f + "сь" : f + "ся");
const HUSH = /[жчшщ]$/;
const out = new Set();
const add = (arr) => { for (const f of arr) if (f) out.add(f); };

// V(inf, type, stem, opts)  type: a (vowel stem, -ю/-ешь), c (consonant stem, -у/-ешь), cё (-у/-ёшь), ii (-ю/-ишь), x (pres given)
function V(inf, t, s, o = {}) {
  let pres;
  if (o.pres) pres = o.pres;
  else if (t === "a") pres = [s + "ю", s + "ешь", s + "ет", s + "ем", s + "ете", s + "ют"];
  else if (t === "c") pres = [s + "у", s + "ешь", s + "ет", s + "ем", s + "ете", s + "ут"];
  else if (t === "cё") pres = [s + "у", s + "ёшь", s + "ёт", s + "ём", s + "ёте", s + "ут"];
  else if (t === "ii") {
    const s1 = o.s1 || s;
    pres = [s1 + (HUSH.test(s1) ? "у" : "ю"), s + "ишь", s + "ит", s + "им", s + "ите", s + (HUSH.test(s) ? "ат" : "ят")];
  } else throw new Error("bad type " + inf);
  let imp = o.imp;
  if (imp === undefined && t === "a") imp = s + "й";
  if (typeof imp === "string") imp = [imp, imp + "те"];
  const b = inf.slice(0, -2);
  const past = o.past || [b + "л", b + "ла", b + "ло", b + "ли"];
  const core = [inf, ...pres, ...(imp || []), ...past];
  const part = [];
  const ger = [];
  const pass = [];
  if (!o.perf) {
    part.push(...adjS(o.act || pres[5].slice(0, -1) + "щ"));
    const r = pres[5].slice(0, -2);
    const g = o.gerP !== undefined ? o.gerP : (pres[5].endsWith("ат") || HUSH.test(r) ? r + "а" : r + "я");
    if (g) ger.push(g);
    if (o.ppp) pass.push(...adjH(pres[3]));
  }
  const pm = past[0];
  const pap = o.pap || (pm.endsWith("л") ? pm.slice(0, -1) + "вш" : pm + "ш");
  part.push(...adjS(pap));
  if ((o.perf || o.pg) && !o.nopg) {
    if (pm.endsWith("л") && !/ш[её]л$/.test(pm)) ger.push(pm.slice(0, -1) + "в", pm.slice(0, -1) + "вши");
    else if (!pm.endsWith("л")) ger.push(pm + "ши");
  }
  if (o.pass) {
    const p = o.pass;
    const long = p.endsWith("т") ? p : p + "н";
    pass.push(...adjH(long));
    const f = p.endsWith("ён") ? p.slice(0, -2) + "ена" : p + "а";
    const n = p.endsWith("ён") ? p.slice(0, -2) + "ено" : p + "о";
    const pl = p.endsWith("ён") ? p.slice(0, -2) + "ены" : p + "ы";
    pass.push(p, f, n, pl);
  }
  if (o.refl) {
    add(core.map(sfx));
    add(part.map((f) => f + "ся"));
    add(ger.map(sfx));
  } else {
    add(core); add(part); add(ger); add(pass);
    if (o.rp) add([inf, pres[2], pres[5], ...past].map(sfx));
  }
}
// -avat' class: uznavat', davat', vstavat'
function AV(inf, o = {}) {
  const s = inf.slice(0, -4);
  const pres = [s + "ю", s + "ёшь", s + "ёт", s + "ём", s + "ёте", s + "ют"];
  V(inf, "x", s, { pres, imp: [inf.slice(0, -2) + "й", inf.slice(0, -2) + "йте"], gerP: inf.slice(0, -2) + "я", ...o });
}
// dat'-class: dat', sozdat', prodat'
function D(inf, base, pass, o = {}) {
  const pres = [base + "м", base + "шь", base + "ст", base + "дим", base + "дите", base + "дут"];
  V(inf, "x", base, { pres, imp: [base + "й", base + "йте"], perf: true, pass, ...o });
}
// -yti verbs (idti + prefix)
function GO(inf, stem, pp, pass) {
  const past = pp === "вы" ? ["вышел", "вышла", "вышло", "вышли"] : [pp + "шёл", pp + "шла", pp + "шло", pp + "шли"];
  V(inf, "cё", stem, { imp: [stem + "и", stem + "ите"], past, pap: pp + "шедш", perf: true, pass, nopg: true });
  add([stem + "я"]);
}

