// Merge a round's fixer outputs and prove every finding got an outcome.
// Reads audit/rounds/NN/{concreteness,consistency,coverage}-*.md (findings tables, rows "| <n> | …")
// and resolution-*-{A,B}.md (rows "| <findings-file>#<n> | … | <outcome> | …").
// Writes audit/rounds/NN/resolution.md and prints: unaccounted findings, outcome counts, the
// "Ownership rows", "Ruleset data" and "Policy keys added" sections, and open xfile requests.
// Usage: node tools/trace/collect-round.mjs 06 [--write]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(fileURLToPath(new URL("../..", import.meta.url)));
const round = process.argv[2];
const dir = path.join(root, "audit/rounds", round || "");
if (!round || !fs.existsSync(dir)) {
  console.error("usage: collect-round.mjs <NN> [--write]");
  process.exit(2);
}
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".md"));
const findingFiles = files.filter((f) => /^(concreteness|consistency|coverage)-.*\.md$/.test(f));
const resolutionFiles = files.filter((f) => /^resolution-.*-[AB]\.md$/.test(f)).sort();

// findings: "<file-stem>#<n>" → row text
const findings = new Map();
for (const f of findingFiles) {
  const stem = f.replace(/\.md$/, "");
  for (const line of fs.readFileSync(path.join(dir, f), "utf8").split(/\r?\n/)) {
    const m = line.match(/^\|\s*([0-9]+)\s*\|/);
    if (m) findings.set(`${stem}#${m[1]}`, line);
  }
}

// outcomes: key → [{ outcome, file, line }]
const outcomes = new Map();
const sections = { "Ownership rows": [], "Ruleset data": [], "Policy keys added": [] };
const OUTCOME = /\b(fixed|adapted|rejected|xfile)\b/i;
for (const f of resolutionFiles) {
  let section = null;
  for (const line of fs.readFileSync(path.join(dir, f), "utf8").split(/\r?\n/)) {
    const h = line.match(/^##\s+(.*)$/);
    if (h) { section = Object.keys(sections).find((k) => h[1].startsWith(k)) || null; continue; }
    if (section && line.trim() && !/^\|\s*-/.test(line)) { sections[section].push(`${f}: ${line}`); continue; }
    const m = line.match(/^\|\s*`?([a-z0-9-]+?)(?:\.md)?`?\s*#\s*([0-9]+)\s*\|(.*)$/i);
    if (!m) continue;
    let stem = m[1].replace(/^audit\/rounds\/[0-9]+\//, "");
    // a bare "concreteness#3" means this fixer group's own findings file
    if (/^(concreteness|consistency|coverage)$/.test(stem)) stem = `${stem}-${f.replace(/^resolution-(.*)-[AB]\.md$/, "$1")}`;
    const key = `${stem}#${m[2]}`;
    const o = (m[3].match(OUTCOME) || [, "unknown"])[1].toLowerCase();
    if (!outcomes.has(key)) outcomes.set(key, []);
    outcomes.get(key).push({ outcome: o, file: f });
  }
}

// A finding is closed when some pass gave it fixed/adapted/rejected; "xfile" alone means a pass-B
// owner still has to apply it.
const closed = (k) => (outcomes.get(k) || []).some((o) => o.outcome !== "xfile" && o.outcome !== "unknown");
const unaccounted = [...findings.keys()].filter((k) => !outcomes.has(k));
const xfileOnly = [...findings.keys()].filter((k) => outcomes.has(k) && !closed(k));
const unknownKeys = [...outcomes.keys()].filter((k) => !findings.has(k));
const counts = {};
for (const k of findings.keys()) {
  const best = (outcomes.get(k) || []).map((o) => o.outcome).find((o) => o !== "xfile") || (outcomes.has(k) ? "xfile" : "MISSING");
  counts[best] = (counts[best] || 0) + 1;
}

console.log(`round ${round}: ${findings.size} findings in ${findingFiles.length} files; resolution files: ${resolutionFiles.length}`);
console.log(`outcomes: ${JSON.stringify(counts)}`);
if (unaccounted.length) console.log(`UNACCOUNTED (${unaccounted.length}): ${unaccounted.slice(0, 15).join(", ")}${unaccounted.length > 15 ? " …" : ""}`);
if (xfileOnly.length) console.log(`XFILE-ONLY, not yet applied (${xfileOnly.length}): ${xfileOnly.slice(0, 15).join(", ")}${xfileOnly.length > 15 ? " …" : ""}`);
if (unknownKeys.length) console.log(`resolution rows naming no known finding (${unknownKeys.length}): ${unknownKeys.slice(0, 20).join(", ")}`);
for (const [k, v] of Object.entries(sections)) console.log(`--- ${k} (${v.length})\n${v.join("\n")}`);
const xdir = path.join(dir, "xfile");
if (fs.existsSync(xdir)) console.log(`--- xfile request files: ${fs.readdirSync(xdir).join(", ") || "none"}`);

if (process.argv.includes("--write")) {
  const out = [
    `# Resolution — round ${round} (generated by tools/trace/collect-round.mjs)`,
    "",
    `Findings: ${findings.size} · outcomes: ${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(", ")}`,
    unaccounted.length || xfileOnly.length ? `**NOT CLOSED:** ${unaccounted.length} unaccounted, ${xfileOnly.length} xfile-only` : "Every finding has a final outcome.",
    "",
    "| Finding | Outcome(s) | Resolution file(s) |",
    "|---|---|---|",
    ...[...findings.keys()].map((k) => `| ${k} | ${(outcomes.get(k) || [{ outcome: "MISSING" }]).map((o) => o.outcome).join(" → ")} | ${(outcomes.get(k) || []).map((o) => o.file).join(", ")} |`),
    "",
  ];
  fs.writeFileSync(path.join(dir, "resolution.md"), out.join("\n"));
}
process.exit(unaccounted.length || xfileOnly.length ? 1 : 0);
